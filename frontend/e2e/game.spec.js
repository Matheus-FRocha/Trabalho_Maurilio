import { test, expect } from '@playwright/test'
test('two independent players join, draw, discard, reconnect and finish', async ({ browser }) => {
  const first = await browser.newContext()
  const second = await browser.newContext()
  const a = await first.newPage(), b = await second.newPage()
  const errors = []
  a.on('pageerror', error => errors.push(error.message)); b.on('pageerror', error => errors.push(error.message))
  await a.goto('/'); await b.goto('/')
  await expect(a.getByTestId('connection')).toHaveText('Conectado')
  await a.screenshot({ path: '../output/screenshots/inicio-desktop.png', fullPage: true })
  await a.getByLabel('Seu nome').fill('Ana')
  await a.getByRole('button', { name: 'Criar uma mesa' }).click()
  const code = await a.getByTestId('room-code').innerText()
  await b.getByRole('button', { name: 'Entrar com código' }).click()
  await b.getByLabel('Seu nome').fill('Beto')
  await b.getByLabel('Código da sala').fill(code)
  await b.getByRole('button', { name: 'Entrar na mesa', exact: true }).click()
  await expect(a.getByText('Beto', { exact: true }).first()).toBeVisible()
  await a.getByRole('button', { name: 'Começar partida' }).click()
  await expect(a.getByTestId('hand-card')).toHaveCount(9)
  await expect(b.getByTestId('hand-card')).toHaveCount(9)
  await a.screenshot({ path: '../output/screenshots/mesa-desktop.png', fullPage: true })
  await expect(b.getByRole('button', { name: 'Comprar do monte' })).toBeDisabled()
  await a.getByRole('button', { name: 'Comprar do monte' }).click()
  await expect(a.getByTestId('hand-card')).toHaveCount(10)
  await a.getByTestId('hand-card').first().click()
  await a.getByRole('button', { name: 'Descartar selecionada' }).click()
  await expect(a.getByTestId('hand-card')).toHaveCount(9)
  await expect(b.getByRole('button', { name: 'Comprar do monte' })).toBeEnabled()
  await b.reload()
  await expect(b.getByTestId('connection')).toHaveText('Conectado')
  await expect(b.getByTestId('hand-card')).toHaveCount(9)
  await b.getByRole('button', { name: 'Comprar do descarte' }).click()
  await expect(b.getByTestId('hand-card')).toHaveCount(10)
  await b.getByTestId('hand-card').last().click()
  await b.getByRole('button', { name: 'Descartar selecionada' }).click()
  await expect(b.getByTestId('hand-card')).toHaveCount(9)
  await a.getByRole('button', { name: 'Sair da partida' }).click()
  await expect(b.getByRole('heading', { name: 'Você venceu!' })).toBeVisible()
  await expect(a.getByRole('heading', { name: 'Partida encerrada' })).toBeVisible()
  expect(errors).toEqual([])
  await first.close(); await second.close()
})
